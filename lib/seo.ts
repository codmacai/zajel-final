interface PageSeo {
  /** Page title without the brand; " | Zajel" is added automatically. */
  title: string;
  description: string;
  /** Route path, e.g. '/air-freight'. Used for the canonical link and social previews. */
  path: string;
  /** Keep the page out of search results (thin, private or per-user pages). */
  noIndex?: boolean;
}

/** Builds consistent metadata for a page: title, description, canonical and social previews. */
export function pageMetadata({ title, description, path, noIndex }: PageSeo): Metadata {
  const fullTitle = title.endsWith(`| ${SITE.name}`) ? title : `${title} | ${SITE.name}`;
  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: path },
    openGraph: {
      type: 'website',
      siteName: SITE.name,
      locale: SITE.locale,
      url: path,
      title: fullTitle,
      description,
      // A page's openGraph replaces the site default, so the preview image is set here too.
      images: [SITE.ogImage],
    },
    twitter: { card: 'summary_large_image', title: fullTitle, description, images: [SITE.ogImage.url] },
    ...(noIndex ? { robots: { index: false, follow: true } } : {}),
  };
}
